#[test]
fn incomplete_gamma_matches_high_precision_references() {
    for &(a, x, p, q) in &REFERENCE {
        for (what, got, want) in [("P", gammainc(a, x), p), ("Q", gammaincc(a, x), q)] {
            let error = ((got - want) / want).abs();
            assert!(
                error < 2e-13,
                "{what}({a:e}, {x:e}) = {got:e}, want {want:e} (relative error {error:.1e})"
            );
        }
    }
}
