//! implementation switches between: the power series, the continued fraction,
//! the small-`x` complement series, and Temme's expansion near `x ≈ a`.
//!
//! The references come from mpmath's `gammainc` at 50 digits, and for `a` of
//! 10¹⁰ and 10¹⁵ from integrating the gamma density at 50 digits. Before Temme's
